using System.Globalization;
using System.Text;
using OpenWorker.Extensions;

namespace OpenWorker.SourceGenerator.ResourceStructures;

/// <summary>
/// Writes the struct of a row of a client table, one property per column, read in the order of the columns. What a row
/// offers beyond its columns is written by hand in a partial struct of the same name (<c>OpenWorker.Res/Members</c>).
/// </summary>
public static class RowWriter
{
    public const string Namespace = "OpenWorker.UpdateContent.Res.Rows";

    /// <summary>
    /// The folder of the rows, from the root of the repository.
    /// </summary>
    public static readonly string[] Folder = ["OpenWorker.Res", "Rows"];

    /// <summary>
    /// The definition of the tables, from the root of the repository.
    /// </summary>
    public static readonly string[] Definition = ["OpenWorker.SourceGenerator.ResourceStructures", "Structures.json"];

    public static string Render(TableDefinition table)
    {
        var usings = new SortedSet<string>(StringComparer.Ordinal) { "OpenWorker.Res.Attributes" };

        foreach (var column in table.Columns)
        {
            if (column.Type == "String")
            {
                usings.Add(typeof(BinaryReaderExtension).Namespace!);
            }

            if (column.As is { } type)
            {
                usings.Add(type[..type.LastIndexOf('.')]);
            }
        }

        var builder = new StringBuilder();

        builder.Append("// <auto-generated>\n");
        builder.Append("// Written by OpenWorker.SourceGenerator.ResourceStructures from Structures.json: change the columns there.\n");
        builder.Append('\n');

        foreach (var name in usings)
        {
            builder.Append(CultureInfo.InvariantCulture, $"using {name};\n");
        }

        builder.Append('\n');
        builder.Append(CultureInfo.InvariantCulture, $"namespace {Namespace};\n");
        builder.Append('\n');
        builder.Append(CultureInfo.InvariantCulture, $"[BinaryResourceTable(\"{table.Table}\")]\n");
        builder.Append(CultureInfo.InvariantCulture, $"public readonly partial struct {table.RowName}(BinaryReader reader)\n");
        builder.Append("{\n");

        foreach (var column in table.Columns)
        {
            var read = column.Type == "String"
                ? $"reader.{nameof(BinaryReaderExtension.ReadUtf16UnicodeStringWithoutTerminator)}()"
                : $"reader.Read{column.Type}()";

            if (column.As is not null)
            {
                read = $"({column.PropertyType}){read}";
            }

            if (column.Comment is { } comment)
            {
                builder.Append("    /// <summary>\n");
                builder.Append(CultureInfo.InvariantCulture, $"    /// {System.Security.SecurityElement.Escape(comment)}\n");
                builder.Append("    /// </summary>\n");
            }

            builder.Append(CultureInfo.InvariantCulture, $"    public {column.PropertyType} {column.Name} {{ get; }} = {read};\n");
        }

        builder.Append("}\n");

        return builder.ToString();
    }

    /// <summary>
    /// The folder that holds <c>OpenWorker.slnx</c>, from a folder inside it.
    /// </summary>
    public static string FindRoot(string start)
    {
        for (var folder = new DirectoryInfo(start); folder is not null; folder = folder.Parent)
        {
            if (File.Exists(Path.Join(folder.FullName, "OpenWorker.slnx")))
            {
                return folder.FullName;
            }
        }

        throw new DirectoryNotFoundException($"No OpenWorker.slnx above {start}.");
    }
}
